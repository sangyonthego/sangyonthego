function getPlaceFromURL() {
  const params = new URLSearchParams(window.location.search);
  return params.get("place");
}

let currentGallery = [];
let currentIndex = 0;

function renderPlace() {
  const placeKey = getPlaceFromURL();

  if (!placeKey || !travelData[placeKey]) {
    console.error("Place not found:", placeKey);
    return;
  }

  const place = travelData[placeKey];

  document.title = `${place.title} | SangyOnTheGo`;

  const heroImage = document.getElementById("place-image");
  if (heroImage) {
    heroImage.src = place.image;
    heroImage.alt = place.title;
  }

  const title = document.getElementById("place-title");
  if (title) {
    title.textContent = place.title;
  }

  const tagline = document.getElementById("place-tagline");
  if (tagline) {
    tagline.textContent = place.tagline;
  }

  const intro = document.getElementById("place-intro");
  if (intro) {
    intro.textContent = place.intro;
  }

  const experiences = document.getElementById("place-experiences");
  if (experiences) {
    experiences.innerHTML = "";
    place.experiences.forEach(experience => {
      const li = document.createElement("li");
      li.textContent = experience;
      experiences.appendChild(li);
    });
  }

  const notes = document.getElementById("place-notes");
  if (notes) {
    notes.textContent = place.notes;
  }

  const gallery = document.getElementById("place-gallery");
  if (gallery) {
    gallery.innerHTML = "";
    currentGallery = place.gallery || [];

    currentGallery.forEach((src, index) => {
      const img = document.createElement("img");
      img.src = src;
      img.alt = `${place.title} photo ${index + 1}`;
      img.classList.add("gallery-img");
      img.addEventListener("click", () => openLightbox(src));
      gallery.appendChild(img);
    });
  }
}

function openLightbox(src) {
  const lightbox = document.getElementById("lightbox");
  const lightboxImg = document.getElementById("lightbox-img");

  if (!lightbox || !lightboxImg) return;

  currentIndex = currentGallery.indexOf(src);
  lightboxImg.src = src;
  lightbox.classList.remove("hidden");
  document.body.style.overflow = "hidden";
}

function closeLightbox() {
  const lightbox = document.getElementById("lightbox");

  if (!lightbox) return;

  lightbox.classList.add("hidden");
  document.body.style.overflow = "";
}

function navigateGallery(direction) {
  if (!currentGallery.length) return;

  currentIndex = (currentIndex + direction + currentGallery.length) % currentGallery.length;

  const lightboxImg = document.getElementById("lightbox-img");

  if (lightboxImg) {
    lightboxImg.src = currentGallery[currentIndex];
  }
}

document.addEventListener("keydown", event => {
  const lightbox = document.getElementById("lightbox");

  if (!lightbox || lightbox.classList.contains("hidden")) return;

  if (event.key === "Escape") {
    closeLightbox();
  }

  if (event.key === "ArrowLeft") {
    navigateGallery(-1);
  }

  if (event.key === "ArrowRight") {
    navigateGallery(1);
  }
});

document.addEventListener("DOMContentLoaded", () => {
  renderPlace();
});
