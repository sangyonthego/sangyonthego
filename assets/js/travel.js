// ===============================
// GET PLACE FROM URL
// ===============================

const params = new URLSearchParams(window.location.search);
const placeKey = params.get("place");

const place = travelData[placeKey];


// ===============================
// HANDLE INVALID PLACE
// ===============================

if (!place) {

  document.title = "Destination Not Found | SangyOnTheGo";

  const title = document.getElementById("place-title");

  if (title) {
    title.textContent = "Destination not found";
  }

} else {

  // ===============================
  // PAGE TITLE
  // ===============================

  document.title = `${place.title} | SangyOnTheGo`;


  // ===============================
  // BASIC CONTENT
  // ===============================

  document.getElementById("place-title").textContent = place.title;

  document.getElementById("place-tagline").textContent =
    place.tagline;

  document.getElementById("place-intro").textContent =
    place.intro;

  document.getElementById("place-notes").textContent =
    place.notes;


  // ===============================
  // HERO IMAGE
  // ===============================

  const placeImage = document.getElementById("place-image");

  if (placeImage) {
    placeImage.src = place.image;
    placeImage.alt = place.title;
  }


  // ===============================
  // EXPERIENCES
  // ===============================

  const experienceList =
    document.getElementById("place-experiences");

  if (experienceList) {

    experienceList.innerHTML = "";

    place.experiences.forEach(experience => {

      const li = document.createElement("li");

      li.textContent = experience;

      experienceList.appendChild(li);

    });
  }


  // ===============================
  // GALLERY
  // ===============================

  const galleryDiv =
    document.getElementById("place-gallery");

  let currentGallery = [];
  let currentIndex = 0;

  if (galleryDiv && place.gallery?.length) {

    currentGallery = place.gallery;

    galleryDiv.innerHTML = "";

    place.gallery.forEach((src, index) => {

      const img = document.createElement("img");

      img.src = src;

      img.alt = `${place.title} photo ${index + 1}`;

      img.classList.add("gallery-img");

      img.addEventListener("click", () => {
        openLightbox(index);
      });

      galleryDiv.appendChild(img);
    });
  }


  // ===============================
  // LIGHTBOX
  // ===============================

  window.openLightbox = function(index) {

    if (!currentGallery.length) return;

    currentIndex = index;

    const lightbox =
      document.getElementById("lightbox");

    const lightboxImg =
      document.getElementById("lightbox-img");

    lightboxImg.src =
      currentGallery[currentIndex];

    lightbox.classList.remove("hidden");
  };


  window.navigateGallery = function(direction) {

    if (!currentGallery.length) return;

    currentIndex =
      (currentIndex + direction + currentGallery.length)
      % currentGallery.length;

    document.getElementById("lightbox-img").src =
      currentGallery[currentIndex];
  };


  window.closeLightbox = function() {

    const lightbox =
      document.getElementById("lightbox");

    lightbox.classList.add("hidden");
  };
}
